-- =========================================================
-- DIVISION
-- A subdivision refers to its parent division.
-- =========================================================

CREATE TABLE division (
                          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          name VARCHAR(150) NOT NULL,
                          original_name VARCHAR(150) NOT NULL,
                          director_name VARCHAR(200) NOT NULL,
                          parent_division_id INTEGER,

                          CONSTRAINT fk_division_parent
                              FOREIGN KEY (parent_division_id)
                                  REFERENCES division (id),

                          CONSTRAINT chk_division_not_own_parent
                              CHECK (parent_division_id <> id)
);


-- =========================================================
-- MEMBERSHIP LEVEL
-- Reduction is stored as a percentage: 20 means 20%.
-- =========================================================

CREATE TABLE membership_level (
                                  code VARCHAR(30) PRIMARY KEY,
                                  monthly_cost NUMERIC(10, 2) NOT NULL,
                                  parking_reduction_percentage INTEGER NOT NULL,
                                  max_allocation_hours INTEGER NOT NULL,

                                  CONSTRAINT chk_membership_monthly_cost
                                      CHECK (monthly_cost >= 0),

                                  CONSTRAINT chk_membership_reduction
                                      CHECK (parking_reduction_percentage BETWEEN 0 AND 100),

                                  CONSTRAINT chk_membership_max_hours
                                      CHECK (max_allocation_hours > 0)
);

