-- =========================================================
-- MEMBER
-- Password is optional because security is optional.
-- If supplied, store a hash, never a plain-text password.
-- =========================================================

CREATE TABLE member (
                        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                        first_name VARCHAR(100) NOT NULL,
                        last_name VARCHAR(100) NOT NULL,

                        street_name VARCHAR(150) NOT NULL,
                        street_number VARCHAR(20) NOT NULL,
                        postal_code VARCHAR(20) NOT NULL,
                        postal_label VARCHAR(150) NOT NULL,

                        phone_number VARCHAR(40) NOT NULL,
                        email VARCHAR(254) NOT NULL,
                        password_hash VARCHAR(255),

                        license_plate_number VARCHAR(30) NOT NULL,
                        license_plate_country VARCHAR(100) NOT NULL,

                        registration_date DATE NOT NULL DEFAULT CURRENT_DATE,
                        role VARCHAR(20) NOT NULL DEFAULT 'USER',
                        membership_code VARCHAR(30) NOT NULL DEFAULT 'BRONZE',

                        CONSTRAINT fk_member_membership
                            FOREIGN KEY (membership_code)
                                REFERENCES membership_level (code),

                        CONSTRAINT chk_member_role
                            CHECK (role IN ('USER', 'MANAGER'))
);


-- =========================================================
-- CONTACT PERSON
-- At least one non-blank phone number is required.
-- =========================================================

CREATE TABLE contact_person (
                                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                name VARCHAR(200) NOT NULL,
                                mobile_phone_number VARCHAR(40),
                                telephone_number VARCHAR(40),
                                email VARCHAR(254) NOT NULL,

                                street_name VARCHAR(150) NOT NULL,
                                street_number VARCHAR(20) NOT NULL,
                                postal_code VARCHAR(20) NOT NULL,
                                postal_label VARCHAR(150) NOT NULL,

                                CONSTRAINT chk_contact_person_phone
                                    CHECK (
                                        NULLIF(TRIM(mobile_phone_number), '') IS NOT NULL
                                            OR
                                        NULLIF(TRIM(telephone_number), '') IS NOT NULL
                                        )
);


-- =========================================================
-- PARKING LOT
-- A contact person can be used by multiple parking lots.
-- =========================================================

CREATE TABLE parking_lot (
                             id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                             name VARCHAR(150) NOT NULL,
                             category VARCHAR(40) NOT NULL,
                             max_capacity INTEGER NOT NULL,
                             price_per_hour NUMERIC(10, 2) NOT NULL,

                             contact_person_id INTEGER NOT NULL,
                             division_id INTEGER NOT NULL,

                             street_name VARCHAR(150) NOT NULL,
                             street_number VARCHAR(20) NOT NULL,
                             postal_code VARCHAR(20) NOT NULL,
                             postal_label VARCHAR(150) NOT NULL,

                             CONSTRAINT fk_parking_lot_contact
                                 FOREIGN KEY (contact_person_id)
                                     REFERENCES contact_person (id),

                             CONSTRAINT fk_parking_lot_division
                                 FOREIGN KEY (division_id)
                                     REFERENCES division (id),

                             CONSTRAINT chk_parking_lot_category
                                 CHECK (
                                     category IN (
                                                  'UNDERGROUND_BUILDING',
                                                  'ABOVE_GROUND_BUILDING'
                                         )
                                     ),

                             CONSTRAINT chk_parking_lot_capacity
                                 CHECK (max_capacity > 0),

                             CONSTRAINT chk_parking_lot_price
                                 CHECK (price_per_hour >= 0)
);


-- =========================================================
-- PARKING SPOT ALLOCATION
-- Store the actual plate used, including for Gold members.
-- =========================================================

CREATE TABLE parking_spot_allocation (
                                         id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                         member_id INTEGER NOT NULL,
                                         parking_lot_id INTEGER NOT NULL,
                                         license_plate_number VARCHAR(30) NOT NULL,

                                         start_time TIMESTAMP WITH TIME ZONE
                                             NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                         end_time TIMESTAMP WITH TIME ZONE,
                                         status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

                                         CONSTRAINT fk_allocation_member
                                             FOREIGN KEY (member_id)
                                                 REFERENCES member (id),

                                         CONSTRAINT fk_allocation_parking_lot
                                             FOREIGN KEY (parking_lot_id)
                                                 REFERENCES parking_lot (id),

                                         CONSTRAINT chk_allocation_status
                                             CHECK (status IN ('ACTIVE', 'STOPPED', 'INVOICED')),

                                         CONSTRAINT chk_allocation_time_order
                                             CHECK (end_time IS NULL OR end_time >= start_time),

                                         CONSTRAINT chk_allocation_status_end_time
                                             CHECK (
                                                 (status = 'ACTIVE' AND end_time IS NULL)
                                                     OR
                                                 (status IN ('STOPPED', 'INVOICED') AND end_time IS NOT NULL)
                                                 )
);


-- =========================================================
-- INDEXES
-- Support relationships, filters and chronological ordering.
-- =========================================================

CREATE INDEX idx_division_parent
    ON division (parent_division_id);

CREATE INDEX idx_member_membership
    ON member (membership_code);

CREATE INDEX idx_parking_lot_division
    ON parking_lot (division_id);

CREATE INDEX idx_parking_lot_contact
    ON parking_lot (contact_person_id);

CREATE INDEX idx_allocation_start_time
    ON parking_spot_allocation (start_time);

CREATE INDEX idx_allocation_status_start_time
    ON parking_spot_allocation (status, start_time);

CREATE INDEX idx_allocation_member_status
    ON parking_spot_allocation (member_id, status);

CREATE INDEX idx_allocation_lot_status
    ON parking_spot_allocation (parking_lot_id, status);