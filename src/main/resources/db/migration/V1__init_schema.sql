CREATE SCHEMA IF NOT EXISTS parkshark;

SET search_path TO parkshark;


-- =========================================================
-- POSTAL CODE
-- label = city/locality, for example: 3000 / Leuven
-- =========================================================

CREATE TABLE postal_code (
                             id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             postal_code VARCHAR(20) NOT NULL,
                             label VARCHAR(150) NOT NULL,

                             CONSTRAINT uq_postal_code
                                 UNIQUE (postal_code, label)
);


-- =========================================================
-- ADDRESS
-- Multiple addresses can refer to the same postal code.
-- =========================================================

CREATE TABLE address (
                         id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         street VARCHAR(150) NOT NULL,
                         number VARCHAR(20) NOT NULL,
                         postal_code_id INTEGER NOT NULL,

                         CONSTRAINT fk_address_postal_code
                             FOREIGN KEY (postal_code_id)
                                 REFERENCES postal_code (id)
);


-- =========================================================
-- LICENSE PLATE
-- The combination of number and issuing country is unique.
-- =========================================================

CREATE TABLE license_plate (
                               id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               number VARCHAR(30) NOT NULL,
                               country VARCHAR(100) NOT NULL,

                               CONSTRAINT uq_license_plate
                                   UNIQUE (number, country)
);


-- =========================================================
-- PERSON
-- Shared account data for members, managers and admins.
-- Name is embedded in Java, stored as two columns here.
-- =========================================================

CREATE TABLE person (
                        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        first_name VARCHAR(100) NOT NULL,
                        last_name VARCHAR(100) NOT NULL,
                        email VARCHAR(254) NOT NULL,
                        password_hash VARCHAR(255) NOT NULL,
                        registration_date DATE NOT NULL DEFAULT CURRENT_DATE,
                        role VARCHAR(20) NOT NULL DEFAULT 'USER',

                        CONSTRAINT uq_person_email
                            UNIQUE (email),

                        CONSTRAINT chk_person_role
                            CHECK (role IN ('USER', 'MANAGER', 'ADMIN'))
);


-- =========================================================
-- MEMBER
-- The member uses the same ID as the corresponding person.
-- The ID is therefore NOT generated again here.
-- =========================================================

CREATE TABLE member (
                        id INTEGER PRIMARY KEY,
                        address_id INTEGER NOT NULL,
                        phone_number VARCHAR(40) NOT NULL,
                        license_plate_id INTEGER NOT NULL,
                        membership VARCHAR(20) NOT NULL DEFAULT 'BRONZE',

                        CONSTRAINT fk_member_person
                            FOREIGN KEY (id)
                                REFERENCES person (id),

                        CONSTRAINT fk_member_address
                            FOREIGN KEY (address_id)
                                REFERENCES address (id),

                        CONSTRAINT fk_member_license_plate
                            FOREIGN KEY (license_plate_id)
                                REFERENCES license_plate (id),

                        CONSTRAINT uq_member_license_plate
                            UNIQUE (license_plate_id),

                        CONSTRAINT chk_member_membership
                            CHECK (membership IN ('BRONZE', 'SILVER', 'GOLD'))
);


-- =========================================================
-- CONTACT PERSON
-- Does not need a member account.
-- One contact person can be linked to several parking lots.
-- =========================================================

CREATE TABLE contact_person (
                                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                first_name VARCHAR(100) NOT NULL,
                                last_name VARCHAR(100) NOT NULL,
                                email VARCHAR(254) NOT NULL,
                                mobile_number VARCHAR(40),
                                phone_number VARCHAR(40),
                                address_id INTEGER NOT NULL,

                                CONSTRAINT fk_contact_person_address
                                    FOREIGN KEY (address_id)
                                        REFERENCES address (id),

                                CONSTRAINT chk_contact_person_phone
                                    CHECK (
                                        NULLIF(TRIM(mobile_number), '') IS NOT NULL
                                            OR
                                        NULLIF(TRIM(phone_number), '') IS NOT NULL
                                        )
);


-- =========================================================
-- DIVISION
-- A division has one director and optionally one parent.
-- =========================================================

CREATE TABLE division (
                          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          name VARCHAR(150) NOT NULL,
                          original_name VARCHAR(150) NOT NULL,
                          director_id INTEGER NOT NULL,
                          subdivision_id INTEGER,

                          CONSTRAINT uq_division_name
                              UNIQUE (name),

                          CONSTRAINT fk_division_director
                              FOREIGN KEY (director_id)
                                  REFERENCES person (id),

                          CONSTRAINT fk_division_parent
                              FOREIGN KEY (parent_division_id)
                                  REFERENCES division (id),

                          CONSTRAINT chk_division_not_own_parent
                              CHECK (parent_division_id <> id)
);


-- =========================================================
-- PARKING LOT
-- UNIQUE address_id implements your One-to-One relationship.
-- ABOVE_STREET represents the above-ground building category.
-- =========================================================

CREATE TABLE parking_lot (
                             id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             name VARCHAR(150) NOT NULL,
                             category VARCHAR(30) NOT NULL,
                             max_capacity INTEGER NOT NULL,
                             price_per_hour_in_euro NUMERIC(10, 2) NOT NULL,
                             contact_person_id INTEGER NOT NULL,
                             address_id INTEGER NOT NULL,
                             division_id INTEGER NOT NULL,

                             CONSTRAINT uq_parking_lot_name
                                 UNIQUE (name),

                             CONSTRAINT uq_parking_lot_address
                                 UNIQUE (address_id),

                             CONSTRAINT fk_parking_lot_contact_person
                                 FOREIGN KEY (contact_person_id)
                                     REFERENCES contact_person (id),

                             CONSTRAINT fk_parking_lot_address
                                 FOREIGN KEY (address_id)
                                     REFERENCES address (id),

                             CONSTRAINT fk_parking_lot_division
                                 FOREIGN KEY (division_id)
                                     REFERENCES division (id),

                             CONSTRAINT chk_parking_lot_category
                                 CHECK (category IN ('UNDERGROUND', 'ABOVE_STREET')),

                             CONSTRAINT chk_parking_lot_capacity
                                 CHECK (max_capacity > 0),

                             CONSTRAINT chk_parking_lot_price
                                 CHECK (price_per_hour_in_euro >= 0)
);


-- =========================================================
-- PARKING SPOT ALLOCATION
-- Store the actual plate used for this allocation.
-- It can differ from the member's plate for Gold members.
-- =========================================================

CREATE TABLE parking_spot_allocation (
                                         id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         member_id INTEGER NOT NULL,
                                         parking_lot_id INTEGER NOT NULL,
                                         license_plate_number VARCHAR(30) NOT NULL,
                                         start_time TIMESTAMP WITH TIME ZONE
                                             NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                         end_time TIMESTAMP WITH TIME ZONE,
                                         status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

                                         CONSTRAINT fk_allocation_member
                                             FOREIGN KEY (member_id)
                                                 REFERENCES member (id),

                                         CONSTRAINT fk_allocation_parking_lot
                                             FOREIGN KEY (parking_lot_id)
                                                 REFERENCES parking_lot (id),

                                         CONSTRAINT chk_allocation_status
                                             CHECK (status IN ('ACTIVE', 'PASSIVE', 'INVOICED')),

                                         CONSTRAINT chk_allocation_time_order
                                             CHECK (end_time IS NULL OR end_time >= start_time),

                                         CONSTRAINT chk_allocation_status_time
                                             CHECK (
                                                 (status = 'ACTIVE' AND end_time IS NULL)
                                                     OR
                                                 (
                                                     status IN ('PASSIVE', 'INVOICED')
                                                         AND end_time IS NOT NULL
                                                     )
                                                 )
);


-- =========================================================
-- INVOICE
-- Membership cost is stored as a snapshot at invoice creation.
-- Total price is calculated from items + membership cost.
-- =========================================================

CREATE TABLE invoice (
                         id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         reference_number VARCHAR(100) NOT NULL,
                         member_id INTEGER NOT NULL,
                         creation_date DATE NOT NULL DEFAULT CURRENT_DATE,
                         expiration_date DATE NOT NULL,
                         status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
                         membership_monthly_cost NUMERIC(10, 2) NOT NULL,
                         payment_date DATE,

                         CONSTRAINT uq_invoice_reference
                             UNIQUE (reference_number),

                         CONSTRAINT fk_invoice_member
                             FOREIGN KEY (member_id)
                                 REFERENCES member (id),

                         CONSTRAINT chk_invoice_status
                             CHECK (status IN ('OPEN', 'CLOSED')),

                         CONSTRAINT chk_invoice_expiration_date
                             CHECK (expiration_date >= creation_date),

                         CONSTRAINT chk_invoice_membership_cost
                             CHECK (membership_monthly_cost >= 0),

                         CONSTRAINT chk_invoice_payment
                             CHECK (
                                 (status = 'OPEN' AND payment_date IS NULL)
                                     OR
                                 (
                                     status = 'CLOSED'
                                         AND payment_date IS NOT NULL
                                         AND payment_date >= creation_date
                                     )
                                 )
);


-- =========================================================
-- INVOICE ITEM
-- One allocation can appear on at most one invoice.
-- Price includes the applied discount and any fine.
-- =========================================================

CREATE TABLE invoice_item (
                              id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              invoice_id INTEGER NOT NULL,
                              parking_spot_allocation_id INTEGER NOT NULL,
                              price NUMERIC(12, 2) NOT NULL,

                              CONSTRAINT fk_invoice_item_invoice
                                  FOREIGN KEY (invoice_id)
                                      REFERENCES invoice (id),

                              CONSTRAINT fk_invoice_item_allocation
                                  FOREIGN KEY (parking_spot_allocation_id)
                                      REFERENCES parking_spot_allocation (id),

                              CONSTRAINT uq_invoice_item_allocation
                                  UNIQUE (parking_spot_allocation_id),

                              CONSTRAINT chk_invoice_item_price
                                  CHECK (price >= 0)
);


