package com.bordeauxbrothers.parkshark.allocation.api.dto;

import com.bordeauxbrothers.parkshark.allocation.domain.AllocationStatus;
import io.swagger.v3.oas.annotations.media.Schema;

import java.time.OffsetDateTime;

@Schema(description = "A parking session of a member in a parking lot.")
public record AllocationDto(

        @Schema(description = "Unique ID of the allocation, generated by the server.", example = "101")
        Integer id,

        @Schema(description = "ID of the member who owns the allocation.", example = "7")
        Integer memberId,

        @Schema(description = "ID of the parking lot where the car is parked.", example = "42")
        Integer parkingLotId,

        @Schema(description = "Licence plate number of the car actually parked.", example = "1-ABC-123")
        String licensePlateNumber,

        @Schema(description = "When the allocation was started.", example = "2026-11-04T10:00:00Z")
        OffsetDateTime startTime,

        @Schema(
                description = "When the allocation was stopped. Null while the allocation is ACTIVE.",
                example = "2026-11-04T12:20:15Z"
        )
        OffsetDateTime endTime,

        @Schema(
                description = """
                        Duration of the allocation in hh:mm:ss.
                        For ACTIVE allocations, measured until now.
                        """,
                example = "02:20:15"
        )
        String duration,

        @Schema(description = "Current status of the allocation.", example = "STOPPED")
        AllocationStatus status
) {
}