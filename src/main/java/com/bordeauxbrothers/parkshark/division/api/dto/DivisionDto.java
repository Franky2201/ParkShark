package com.bordeauxbrothers.parkshark.division.api.dto;

import com.fasterxml.jackson.annotation.JsonInclude;
import io.swagger.v3.oas.annotations.media.Schema;

/**
 * Response DTO for a division.
 * {@code ParentDivisionDto} is only present in the JSON for subdivisions.
 */
@Schema(description = "A division of ParkShark: a company that was taken over.")
public record DivisionDto(

        @Schema(description = "Unique ID of the division, generated by the server.", example = "2")
        int id,

        @Schema(description = "Current name of the division within ParkShark.", example = "Shark North - Antwerp")
        String name,

        @Schema(description = "Name of the company before it was taken over.", example = "Garage Peeters BV")
        String originalName,

        @Schema(description = "ID of the person who directs the division.", example = "5")
        int directorId,

        @Schema(description = "Parent division. Only present for subdivisions.")
        @JsonInclude(JsonInclude.Include.NON_NULL)
        ParentDivisionDto parentDivision
) {
}