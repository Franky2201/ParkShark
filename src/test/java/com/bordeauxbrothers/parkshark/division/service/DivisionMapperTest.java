package com.bordeauxbrothers.parkshark.division.service;

import com.bordeauxbrothers.parkshark.division.api.dto.DivisionDto;
import com.bordeauxbrothers.parkshark.division.domain.Division;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.test.util.ReflectionTestUtils;

import static org.junit.jupiter.api.Assertions.*;

class DivisionMapperTest {

    private final DivisionMapper mapper = new DivisionMapper();

    @Test
    @DisplayName("top-level division maps all fields and has no parent")
    void toDto_topLevelDivision() {
        Division division = divisionWithId(1, "ParkShark North", "Northern Parking Ltd", 42);

        DivisionDto dto = mapper.toDto(division);

        assertEquals(1, dto.id());
        assertEquals("ParkShark North", dto.name());
        assertEquals("Northern Parking Ltd", dto.originalName());
        assertEquals(42, dto.directorId());
        assertNull(dto.parentDivision());
    }

    @Test
    @DisplayName("subdivision includes parent id and name")
    void toDto_subdivision_includesParentIdAndName() {
        Division parent = divisionWithId(1, "ParkShark North", "Northern Parking Ltd", 42);
        Division child = divisionWithId(2, "ParkShark Leuven", "Leuven Lots BV", 7);
        parent.addSubdivision(child);

        DivisionDto dto = mapper.toDto(child);

        assertNotNull(dto.parentDivision());
        assertEquals(1, dto.parentDivision().id());
        assertEquals("ParkShark North", dto.parentDivision().name());
    }

    @Test
    @DisplayName("subdivision keeps its own fields, not the parent's")
    void toDto_subdivision_mapsOwnFields() {
        Division parent = divisionWithId(1, "ParkShark North", "Northern Parking Ltd", 42);
        Division child = divisionWithId(2, "ParkShark Leuven", "Leuven Lots BV", 7);
        parent.addSubdivision(child);

        DivisionDto dto = mapper.toDto(child);

        assertEquals(2, dto.id());
        assertEquals("ParkShark Leuven", dto.name());
        assertEquals("Leuven Lots BV", dto.originalName());
        assertEquals(7, dto.directorId());
    }

    /**
     * The id is normally generated by the database, so in a plain unit test
     * we set it via reflection. Test-only trick: never do this in production code.
     */
    private Division divisionWithId(int id, String name, String originalName, int directorId) {
        Division division = new Division(name, originalName, directorId);
        ReflectionTestUtils.setField(division, "id", id);
        return division;
    }
}